/**
 * Serve event banners and editor files.
 *
 * @param stdClass $course
 * @param stdClass $cm
 * @param context $context
 * @param string $filearea
 * @param array $args
 * @param bool $forcedownload
 * @param array $options
 * @return bool
 */
function local_eventbooking_pluginfile($course, $cm, $context, $filearea, $args, $forcedownload, array $options = []) {
    if ($context->contextlevel != CONTEXT_SYSTEM) {
        return false;
    }
    if (!in_array($filearea, ['banner', 'intro', 'marketing'], true)) {
        return false;
    }

    require_login(null, false);
    if (!has_capability('local/eventbooking:view', $context) &&
            !has_capability('local/eventbooking:manage', $context)) {
        return false;
    }

    $itemid = (int) array_shift($args);
    $filename = array_pop($args);
    if ($filename === null) {
        return false;
    }
    $filepath = $args ? '/' . implode('/', $args) . '/' : '/';

    $fs = get_file_storage();
    $file = $fs->get_file($context->id, 'local_eventbooking', $filearea, $itemid, $filepath, $filename);
    if (!$file || $file->is_directory()) {
        return false;
    }

    send_stored_file($file, 0, 0, $forcedownload, $options);
}
